"""
Random Forest and XGBoost baselines on concatenated frozen ESM-2 embeddings,
evaluated under the SAME 5-fold splits (random / cold_target / sequence_similarity)
already used for BALM-PPI, as additional sequence-based comparators for the
rebuttal (Referee 3 point 4 / Referee 2 point 5: "a more direct quantitative
comparison against one or two of the sequence-based methods discussed in the
Introduction... would make the comparative claims more convincing").

Features: concatenation of frozen (non-task-tuned) ESM-2-650M mean-pooled
embeddings for Target and proteina (1280 + 1280 = 2560-dim), reusing
cached_embeddings/protein_embeddings.pkl (Target side) and
cached_embeddings/proteina_embeddings.pkl (proteina side, generated by
generate_missing_proteina_embeddings.py to match the same frozen methodology).
This makes RF/XGBoost a genuinely independent, "off-the-shelf embeddings + simple
ML" baseline -- not contaminated by our own LoRA fine-tuning -- directly
comparable in spirit to the existing concatenation-regressor baseline (Table S2)
but with classical, non-neural models instead of an MLP.

Splits: reuses the same K-mer Jaccard sequence-similarity clustering as the
paper's Methods (see train_multiseed_cv.py) for the "sequence_similarity" split,
and GroupKFold by PDB for "cold_target", and plain KFold for "random" -- matching
the splits already used for every other model in the paper.
"""
import pickle
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.cluster.hierarchy import fcluster, linkage
from scipy.spatial.distance import squareform
from scipy.stats import pearsonr, spearmanr
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_squared_error
from sklearn.model_selection import GroupKFold, KFold
import xgboost as xgb

warnings.filterwarnings("ignore")

DATA_CSV = Path("BALM-PPI/scripts/notebooks/Data.csv")
TARGET_EMB_PATH = Path("cached_embeddings/protein_embeddings.pkl")
PROTEINA_EMB_PATH = Path("cached_embeddings/proteina_embeddings.pkl")
N_SPLITS = 5
SEED = 42
K_MER = 3
SIM_THRESHOLD = 0.3


def load_data():
    df = pd.read_csv(DATA_CSV)
    df = df.dropna(subset=["Target", "proteina", "Y", "PDB"]).reset_index(drop=True)
    with open(TARGET_EMB_PATH, "rb") as f:
        target_emb = pickle.load(f)
    with open(PROTEINA_EMB_PATH, "rb") as f:
        proteina_emb = pickle.load(f)

    keep = df["Target"].isin(target_emb) & df["proteina"].isin(proteina_emb)
    n_dropped = (~keep).sum()
    if n_dropped:
        print(f"Dropping {n_dropped} rows missing an embedding (of {len(df)}).")
    df = df[keep].reset_index(drop=True)

    X = np.stack(
        [
            np.concatenate([target_emb[t], proteina_emb[p]])
            for t, p in zip(df["Target"], df["proteina"])
        ]
    )
    y = df["Y"].to_numpy(dtype=np.float32)
    return df, X, y


def get_random_folds(n_rows):
    kf = KFold(n_splits=N_SPLITS, shuffle=True, random_state=SEED)
    return list(kf.split(np.arange(n_rows)))


def get_cold_folds(df):
    gkf = GroupKFold(n_splits=N_SPLITS)
    groups = df["PDB"].factorize()[0]
    return list(gkf.split(df, groups=groups))


def get_sequence_similarity_folds(df):
    all_sequences = sorted(set(df["Target"]) | set(df["proteina"]))
    seq_to_idx = {s: i for i, s in enumerate(all_sequences)}

    def get_kmers(seq):
        if len(seq) < K_MER:
            return {seq}
        return {seq[i : i + K_MER] for i in range(len(seq) - K_MER + 1)}

    kmer_sets = [get_kmers(s) for s in all_sequences]
    n = len(all_sequences)
    sim = np.zeros((n, n))
    for i in range(n):
        sim[i, i] = 1.0
        for j in range(i + 1, n):
            inter = len(kmer_sets[i] & kmer_sets[j])
            union = len(kmer_sets[i] | kmer_sets[j])
            s = inter / union if union > 0 else 0.0
            sim[i, j] = sim[j, i] = s
    dist = 1.0 - sim
    condensed = squareform(dist, checks=False)
    Z = linkage(condensed, method="average")
    clusters = fcluster(Z, t=1.0 - SIM_THRESHOLD, criterion="distance") - 1
    cluster_ids = sorted(set(clusters))

    kf = KFold(n_splits=N_SPLITS, shuffle=True, random_state=SEED)
    seq_cluster = {s: clusters[seq_to_idx[s]] for s in all_sequences}

    folds = []
    for train_c_idx, test_c_idx in kf.split(cluster_ids):
        train_clusters = {cluster_ids[i] for i in train_c_idx}
        test_clusters = {cluster_ids[i] for i in test_c_idx}
        seq_group = {
            s: ("test" if c in test_clusters else "train") for s, c in seq_cluster.items()
        }
        train_idx, test_idx = [], []
        for idx, row in df.iterrows():
            if seq_group.get(row["Target"]) == "test" or seq_group.get(row["proteina"]) == "test":
                test_idx.append(idx)
            else:
                train_idx.append(idx)
        folds.append((np.array(train_idx), np.array(test_idx)))
    return folds


def concordance_index(y_true, y_pred):
    y_true, y_pred = np.asarray(y_true), np.asarray(y_pred)
    n = len(y_true)
    if n < 2:
        return 1.0
    concordant = discordant = tied = 0
    for i in range(n):
        for j in range(i + 1, n):
            if y_true[i] == y_true[j]:
                continue
            if y_pred[i] == y_pred[j]:
                tied += 1
            elif (y_pred[i] > y_pred[j]) == (y_true[i] > y_true[j]):
                concordant += 1
            else:
                discordant += 1
    total = concordant + discordant + tied
    return 1.0 if total == 0 else (concordant + 0.5 * tied) / total


def evaluate_fold(model_ctor, X_train, y_train, X_test, y_test):
    model = model_ctor()
    model.fit(X_train, y_train)
    preds = model.predict(X_test)
    return {
        "rmse": float(np.sqrt(mean_squared_error(y_test, preds))),
        "pearson": float(pearsonr(y_test, preds)[0]),
        "spearman": float(spearmanr(y_test, preds)[0]),
        "ci": float(concordance_index(y_test, preds)),
    }


def run_all(X, y, folds, split_name, results):
    model_ctors = {
        "RandomForest": lambda: RandomForestRegressor(
            n_estimators=300, max_depth=None, n_jobs=-1, random_state=SEED
        ),
        "XGBoost": lambda: xgb.XGBRegressor(
            n_estimators=300, max_depth=6, learning_rate=0.05, n_jobs=-1, random_state=SEED,
            tree_method="hist",
        ),
    }
    for model_name, ctor in model_ctors.items():
        fold_metrics = []
        for fold_i, (train_idx, test_idx) in enumerate(folds, start=1):
            m = evaluate_fold(ctor, X[train_idx], y[train_idx], X[test_idx], y[test_idx])
            print(f"[{split_name}][{model_name}] fold {fold_i}: {m}")
            fold_metrics.append(m)
        df_m = pd.DataFrame(fold_metrics)
        summary = {f"{k}_mean": df_m[k].mean() for k in df_m.columns}
        summary.update({f"{k}_std": df_m[k].std() for k in df_m.columns})
        summary["split"] = split_name
        summary["model"] = model_name
        results.append(summary)


def main():
    print("Loading data and cached frozen ESM-2 embeddings...")
    df, X, y = load_data()
    print(f"Dataset: {len(df)} rows, feature dim {X.shape[1]}")

    results = []

    print("\n=== RANDOM SPLIT ===")
    run_all(X, y, get_random_folds(len(df)), "random", results)

    print("\n=== COLD_TARGET SPLIT ===")
    run_all(X, y, get_cold_folds(df), "cold_target", results)

    print("\n=== SEQUENCE_SIMILARITY SPLIT ===")
    run_all(X, y, get_sequence_similarity_folds(df), "sequence_similarity", results)

    out = pd.DataFrame(results)
    out_path = Path("BALM-PPI/scripts/classical_baseline_results.csv")
    out.to_csv(out_path, index=False)
    print(f"\nSaved summary to {out_path}")
    print(out[["split", "model", "rmse_mean", "rmse_std", "pearson_mean", "pearson_std", "spearman_mean", "spearman_std"]])


if __name__ == "__main__":
    main()
